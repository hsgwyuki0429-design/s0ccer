/**
 * ゲーム定数。単位は SI（メートル・秒）で統一する。
 *
 * ここの値はサーバーとクライアントで完全に共有される。片方だけ変えると
 * クライアント予測がサーバーと食い違い、常時ガタつく原因になる。
 */

/** シミュレーションのティックレート。固定タイムステップ。 */
export const TICK_RATE = 60;
export const DT = 1 / TICK_RATE;

// ---------------------------------------------------------------------------
// ピッチ
// ---------------------------------------------------------------------------

/** ピッチの寸法。原点はセンターサークル、x が長辺方向。 */
export const PITCH_WIDTH = 50;
export const PITCH_HEIGHT = 32;
export const HALF_W = PITCH_WIDTH / 2;
export const HALF_H = PITCH_HEIGHT / 2;

/** ゴールの内寸。GK がいないぶん実際のフットサル（3m）より少しだけ広い程度に抑える。 */
export const GOAL_WIDTH = 3.2;
/** ゴールネットの奥行き。描画とボール停止にのみ使う。 */
export const GOAL_DEPTH = 1.5;

/**
 * ゴールエリアの半径。GK を置かない代わりに、この半円へは
 * 攻守どちらのプレイヤーも侵入できない。ボールは自由に通過する。
 *
 * 暫定値。GOAL_WIDTH と合わせてプレイテストで詰める。
 */
export const GOAL_AREA_RADIUS = 5.5;

export const CENTER_CIRCLE_RADIUS = 4.5;

// ---------------------------------------------------------------------------
// プレイヤー
// ---------------------------------------------------------------------------

export const PLAYER_RADIUS = 0.5;
export const PLAYER_MAX_SPEED = 7.0;
/** 加速・減速のレート。減速を速くすると切り返しがキビキビする。 */
export const PLAYER_ACCEL = 34;
export const PLAYER_DECEL = 46;

// ---------------------------------------------------------------------------
// ボール
// ---------------------------------------------------------------------------

export const BALL_RADIUS = 0.16;
/** 1秒あたりに残る速度の割合。転がり抵抗。 */
export const BALL_DAMPING = 0.5;
/** この速度を下回ったら停止扱いにする。微小振動の除去。 */
export const BALL_STOP_SPEED = 0.05;
/** 壁・ゴールポストへの反発係数。 */
export const BALL_RESTITUTION = 0.72;
/**
 * プレイヤーの体に当たったときの反発係数。
 *
 * 壁と同じ値にすると、走ってボールに追いついた瞬間にボールが自分より速く
 * 弾き飛ばされ、二度と追いつけなくなる。体に当てるのは「当たり負け」であって
 * 「跳ね返り」ではないので、低く抑える。
 */
export const PLAYER_BALL_RESTITUTION = 0.35;
export const BALL_MAX_SPEED = 30;

// ---------------------------------------------------------------------------
// ボールコントロール
// ---------------------------------------------------------------------------

/** この距離内にボールがあればドリブル・キックができる。 */
export const CONTROL_RADIUS = 1.2;
/** ドリブル時、進行方向のどれだけ前にボールを置くか。 */
export const DRIBBLE_DISTANCE = 0.95;
/** ドリブルでボールに与えられる最大加速度。大きいほどボールが足に吸い付く。 */
export const DRIBBLE_ACCEL = 34;
/** これ未満の速度で動いていてもドリブルは発生しない。 */
export const DRIBBLE_MIN_SPEED = 0.4;

// ---------------------------------------------------------------------------
// キック
// ---------------------------------------------------------------------------

/** チャージが最大に達するまでの秒数。 */
export const CHARGE_TIME_MAX = 0.6;
export const KICK_SPEED_MIN = 9;
export const KICK_SPEED_MAX = 28;
/** キック後、次にキックできるまでの秒数。自分で蹴って自分で追う暴走を防ぐ。 */
export const KICK_COOLDOWN = 0.22;
